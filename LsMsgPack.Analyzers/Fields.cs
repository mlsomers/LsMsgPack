using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using System;
using System.Collections.Generic;

namespace LsMsgPack.Analyzers
{
  /// <summary>
  /// The fields the serializers write, as LsMsgPack.Core decides it (FullPropertyInfo.AddFieldCandidates / IsFieldCandidate, PropertyAttributeSet.OptsIn) and LtMsgPack's source generator mirrors it
  /// (TypeWalker.IsFieldCandidate, OptsIn: keep the three equal).
  /// <para>The runtime takes the mode from the static filters (FilterNonSettable's SerializedFields), which the analyzers cannot see: they read the MSBuild property <c>LsMsgPackFields</c>
  /// (declared in buildTransitive/LsMsgPack.Core.props) and <c>[assembly: LtMsgPackGenerate(Fields = ...)]</c> (wins, as for the generator). <see cref="Attributed"/> by default.</para>
  /// </summary>
  internal static class Fields
  {
    // The values of LsMsgPack.TypeResolving.Filters.SerializedFields
    public const int None = 0;
    public const int Attributed = 1;
    public const int Public = 2;
    public const int All = 3;

    /// <summary>
    /// The mode the project says the runtime uses: <c>[assembly: LtMsgPackGenerate(Fields = ...)]</c>, otherwise the MSBuild property <c>LsMsgPackFields</c>, otherwise <see cref="Attributed"/>.
    /// </summary>
    public static int ModeOf(Compilation compilation, AnalyzerOptions options)
    {
      int mode = Attributed;
      if (options.AnalyzerConfigOptionsProvider.GlobalOptions.TryGetValue("build_property.LsMsgPackFields", out string text) && !string.IsNullOrWhiteSpace(text))
        mode = Parse(text, mode);
      foreach (AttributeData attribute in compilation.Assembly.GetAttributes())
      {
        if (attribute.AttributeClass?.ToDisplayString() != "LtMsgPack.LtMsgPackGenerateAttribute")
          continue;
        foreach (KeyValuePair<string, TypedConstant> argument in attribute.NamedArguments)
          if (argument.Key == "Fields" && argument.Value.Value is int value && value >= None && value <= All)
            mode = value;
      }
      return mode;
    }

    /// <summary>
    /// "None", "Attributed", "Public" or "All" (ignoring case, as LtMsgPackGenerator.ParseFields), <paramref name="fallback"/> for anything else.
    /// </summary>
    internal static int Parse(string text, int fallback)
    {
      switch (text.Trim().ToLowerInvariant())
      {
        case "none":
        case "false": return None;
        case "attributed": return Attributed;
        case "public": return Public;
        case "all": return All;
        default: return fallback;
      }
    }

    /// <summary>
    /// The runtime writes the field with the mode (FullPropertyInfo.IsFieldCandidate): a field of state (<see cref="IsOfState"/>), selected by the mode. Fields of the framework's types are not
    /// in source, so they never get here. Ignore attributes and readonly fields are left to the caller (FilterIgnoredAttribute, FilterNonSettable).
    /// </summary>
    public static bool IsSerialized(IFieldSymbol field, int mode)
    {
      if (mode == None || !IsOfState(field))
        return false;
      switch (mode)
      {
        case All: return true;
        case Public: return field.DeclaredAccessibility == Accessibility.Public || OptsIn(field);
        default: return OptsIn(field);
      }
    }

    /// <summary>
    /// A field that may be serialized at all, whatever the mode: an instance field, not const, not generated by the compiler (backing fields of auto-properties and events; names with &lt; or VB's $: static locals, anonymous types),
    /// not a fixed-size buffer, not of a pointer or ref struct type, not the field of a field-like event.
    /// </summary>
    public static bool IsOfState(IFieldSymbol field)
    {
      if (field.IsStatic || field.IsConst || field.IsImplicitlyDeclared || field.AssociatedSymbol != null || field.Name.IndexOf('<') >= 0 || field.Name.IndexOf('$') >= 0 || field.IsFixedSizeBuffer)
        return false;
      foreach (AttributeData attribute in field.GetAttributes())
        if (attribute.AttributeClass?.ToDisplayString() == "System.Runtime.CompilerServices.CompilerGeneratedAttribute")
          return false;
      ITypeSymbol type = field.Type;
      if (type.TypeKind == TypeKind.Pointer || type.TypeKind == TypeKind.FunctionPointer || type.IsRefLikeType)
        return false;
      if (type.TypeKind == TypeKind.Delegate)
        foreach (ISymbol other in field.ContainingType.GetMembers(field.Name))
          if (other is IEventSymbol)
            return false;
      return true;
    }

    /// <summary>
    /// An attribute that opts the member in (LsMsgPack.Core's IncludeAttributes): [JsonInclude], Json.NET's [JsonProperty], [DataMember], [Key] (MessagePack-CSharp, Nerdbank.MessagePack),
    /// [PropertyShape] (not with Ignore = true), any other attribute with "Include" in its name.
    /// </summary>
    public static bool OptsIn(ISymbol member)
    {
      foreach (AttributeData attribute in member.GetAttributes())
      {
        INamedTypeSymbol type = attribute.AttributeClass;
        if (type is null)
          continue;
        switch (type.ToDisplayString())
        {
          case "System.Text.Json.Serialization.JsonIncludeAttribute":
          case "Newtonsoft.Json.JsonPropertyAttribute":
          case "System.Runtime.Serialization.DataMemberAttribute":
          case "MessagePack.KeyAttribute":
          case "Nerdbank.MessagePack.KeyAttribute":
            return true;
          case "PolyType.PropertyShapeAttribute":
            bool ignored = false;
            foreach (KeyValuePair<string, TypedConstant> argument in attribute.NamedArguments)
              ignored |= argument.Key == "Ignore" && argument.Value.Value is bool ignore && ignore;
            if (!ignored)
              return true;
            break;
          default:
            if (type.Name.IndexOf("Include", StringComparison.Ordinal) >= 0)
              return true;
            break;
        }
      }
      return false;
    }

    /// <summary>
    /// The type declares its members for serializers that only write the members marked for them (<c>[DataContract]</c>, MessagePack-CSharp's <c>[MessagePackObject]</c> with keys,
    /// not with <c>keyAsPropertyName: true</c>, which writes every public member): a public field without such a mark is left out on purpose.
    /// </summary>
    public static bool MarksItsMembers(INamedTypeSymbol type)
    {
      foreach (AttributeData attribute in type.GetAttributes())
      {
        switch (attribute.AttributeClass?.ToDisplayString())
        {
          case "System.Runtime.Serialization.DataContractAttribute":
            return true;
          case "MessagePack.MessagePackObjectAttribute":
            if (!(attribute.ConstructorArguments.Length > 0 && attribute.ConstructorArguments[0].Value is bool byName && byName))
              return true;
            break;
        }
      }
      return false;
    }

    /// <summary>
    /// GetOnlyCollection.IsFillable: a reader fills the collection a readonly field (or a property without a setter) holds: an IList, IDictionary or ICollection&lt;T&gt;, not an array or string.
    /// </summary>
    public static bool IsFillable(ITypeSymbol type)
    {
      if (type.TypeKind == TypeKind.Array || type.SpecialType == SpecialType.System_String)
        return false;
      if (IsFillableInterface(type))
        return true;
      foreach (INamedTypeSymbol i in type.AllInterfaces)
        if (IsFillableInterface(i))
          return true;
      return false;
    }

    private static bool IsFillableInterface(ITypeSymbol type)
    {
      if (type.TypeKind != TypeKind.Interface)
        return false;
      if (type.OriginalDefinition.SpecialType == SpecialType.System_Collections_Generic_ICollection_T)
        return true;
      string name = type.ToDisplayString();
      return name == "System.Collections.IList" || name == "System.Collections.IDictionary";
    }

    /// <summary>
    /// SerializationRules.IsNeverWritten: System.Type, MemberInfo (and the classes deriving from them) and delegates, also as the elements of an array. A field of such a type makes writing throw.
    /// </summary>
    public static bool IsNeverWritten(ITypeSymbol type)
    {
      while (type is IArrayTypeSymbol array)
        type = array.ElementType;
      if (type.TypeKind == TypeKind.Delegate)
        return true;
      for (ITypeSymbol t = type; t != null; t = t.BaseType)
      {
        string name = t.ToDisplayString();
        if (name == "System.Type" || name == "System.Reflection.MemberInfo")
          return true;
      }
      return false;
    }
  }
}
