using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;

namespace LtMsgPack.Generator
{
  /// <summary>
  /// Writes the code of the contexts. C# 7.3 only (projects for .NET Framework): no ??=, switch expressions, static lambdas, "is not", #nullable.
  /// </summary>
  internal static class Emitter
  {
    /// <summary>
    /// The version of the generated code (LsMsgPack.Generated.GeneratedContract.Current of the runtime this generator is released with, checked by a test).
    /// </summary>
    internal const int ContractVersion = 3;

    private const string Values = "global::LtMsgPack.Generated.GeneratedValues";

    public static void Emit(SourceProductionContext output, ImmutableArray<ContextModel> declared, ContextModel assembly, GenerateOptions options)
    {
      List<ContextModel> contexts = new List<ContextModel>();
      HashSet<string> names = new HashSet<string>();
      foreach (ContextModel context in declared)
      {
        if (context is null || !names.Add(context.FullName)) // a partial class with the attribute on several declarations
          continue;
        contexts.Add(context);
      }
      if (assembly != null)
        contexts.Add(assembly);

      if (options.Unoptimized && contexts.Exists(c => c.FullName != null && !HasErrors(c))) // once per compilation, there is code to optimize
        output.ReportDiagnostic(Diagnostic.Create(Diagnostics.Unoptimized, null));

      List<ContextModel> registered = new List<ContextModel>();
      HashSet<string> files = new HashSet<string>();
      foreach (ContextModel context in contexts)
      {
        foreach (DiagnosticInfo diagnostic in context.Diagnostics)
          if (options.Trimmed || diagnostic.Id != Diagnostics.Uncovered.Id) // LTMP010 only matters when trimmed or compiled ahead of time
            output.ReportDiagnostic(diagnostic.ToDiagnostic());
        if (context.FullName is null || HasErrors(context))
          continue;

        string file = FileName(context.FullName);
        for (int t = 2; !files.Add(file); t++)
          file = FileName(context.FullName) + t;
        output.AddSource(file + ".LtMsgPack.g.cs", SourceText.From(Context(context, options), Encoding.UTF8));

        if (!options.AutoRegister)
          continue;
        if (!options.ModuleInitializers)
          output.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotRegistered, null, context.FullName.Replace("global::", ""), "module initializers need C# 9 or later"));
        else if (!context.CanRegister)
          output.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotRegistered, null, context.FullName.Replace("global::", ""), "it is not accessible to a class of the assembly"));
        else
          registered.Add(context);
      }

      if (registered.Count > 0)
        output.AddSource("LtMsgPack.Registration.g.cs", SourceText.From(Registration(registered, options), Encoding.UTF8));
    }

    private static bool HasErrors(ContextModel context)
    {
      foreach (DiagnosticInfo diagnostic in context.Diagnostics)
        if (Diagnostics.Get(diagnostic.Id).DefaultSeverity == DiagnosticSeverity.Error)
          return true;
      return false;
    }

    private static string FileName(string fullName)
    {
      StringBuilder name = new StringBuilder();
      foreach (char c in fullName.Replace("global::", ""))
        name.Append(char.IsLetterOrDigit(c) || c == '.' || c == '_' ? c : '_');
      return name.ToString();
    }

    private static string Context(ContextModel context, GenerateOptions options)
    {
      CodeWriter w = new CodeWriter();
      w.Line("// <auto-generated/>");
      w.Line("// Written by LtMsgPack's source generator, see LtMsgPack.LtMsgPackContext.");
      w.Line("#pragma warning disable CS0612, CS0618 // obsolete members are serialized like the others");
      w.Line();
      if (context.Namespace != null)
      {
        w.Line("namespace " + context.Namespace);
        w.Open();
      }
      foreach (StringValue containing in context.ContainingTypes)
      {
        w.Line("partial class " + containing.Value);
        w.Open();
      }

      if (context.DeclaredByUser)
        w.Line("partial class " + context.Name);
      else
      {
        w.Line("/// <summary>");
        w.Line("/// The code of LtMsgPack's source generator for the types of this assembly (LtMsgPackGenerate).");
        w.Line("/// </summary>");
        w.Line("internal sealed partial class " + context.Name + " : global::LtMsgPack.LtMsgPackContext");
      }
      w.Open();

      w.Line("/// <summary>");
      w.Line("/// The instance of this context (the one the module initializer registers, when it does).");
      w.Line("/// </summary>");
      w.Line("public static " + context.Name + " Default { get; } = new " + context.Name + "();");
      w.Line();
      w.Line("/// <summary>");
      w.Line("/// Written by the generator (version " + ContractVersion + " of the generated code).");
      w.Line("/// </summary>");
      w.Line("public " + context.Name + "() : base(" + ContractVersion + ")");
      w.Open();
      w.Close();
      w.Line();

      if (options.HasDynamicDependency)
      {
        foreach (TypeModel type in context.Types)
        {
          if (type.Kind == TypeModelKind.Factory) // the runtime finds CreateRange, ToFrozenSet... by reflection
            w.Line("[global::System.Diagnostics.CodeAnalysis.DynamicDependency(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicMethods, typeof(" + type.TypeName + "))]");
          else if (type.KeepMetadata) // the runtime reads the properties and constructors by reflection: kept when trimming
            w.Line("[global::System.Diagnostics.CodeAnalysis.DynamicDependency(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicProperties"
              + (type.KeepNonPublic ? " | global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.NonPublicProperties" : "")
              + " | global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicConstructors | global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.NonPublicConstructors, typeof("
              + type.TypeName + "))]");
        }
      }
      Accessors accessors = new Accessors();
      // The types by number, each described when it is first looked up (GeneratedContext.Describe), by a class of its own: its lambdas are in a closure class of their own too,
      // which is only loaded with it. Everything at once took 190 ms for 86 types with 1060 properties.
      w.Line("protected override void AddTypes(global::LsMsgPack.Generated.GeneratedTypeSet types)");
      w.Open();
      for (int t = 0; t < context.Types.Length; t++)
        if (context.Types[t].Kind != TypeModelKind.Factory) // a DynamicDependency only
          w.Line("types.Add(typeof(" + context.Types[t].TypeName + "), " + t + ");");
      w.Close();
      w.Line();
      w.Line("protected override global::LsMsgPack.Generated.GeneratedType Describe(int number)");
      w.Open();
      w.Line("switch (number)");
      w.Open();
      for (int t = 0; t < context.Types.Length; t++)
        if (context.Types[t].Kind != TypeModelKind.Factory)
          w.Line("case " + t + ": return " + DescriptionClass(t) + ".Describe();");
      w.Line("default: return null;");
      w.Close();
      w.Close();

      for (int t = 0; t < context.Types.Length; t++)
      {
        if (context.Types[t].Kind == TypeModelKind.Factory)
          continue;
        w.Line();
        w.Line("private static class " + DescriptionClass(t));
        w.Open();
        w.Line("internal static global::LsMsgPack.Generated.GeneratedType Describe()");
        w.Open();
        Description(w, context.Types[t], t, accessors);
        w.Close();
        w.Close();
      }

      for (int t = 0; t < context.Types.Length; t++)
      {
        if (context.Types[t].Members.Length == 0)
          continue;
        w.Line();
        ObjectCode(w, context.Types[t], t, accessors);
      }
      accessors.Write(w);

      w.Close();
      for (int t = 0; t < context.ContainingTypes.Length; t++)
        w.Close();
      if (context.Namespace != null)
        w.Close();
      return w.ToString();
    }

    /// <summary>
    /// The statement returning the description of the type.
    /// </summary>
    private static void Description(CodeWriter w, TypeModel type, int index, Accessors accessors)
    {
      switch (type.Kind)
      {
        case TypeModelKind.Enum:
          w.Line("return " + Values + ".Enum<" + type.TypeName + ">();");
          return;
        case TypeModelKind.Nullable:
          w.Line("return " + Values + ".Nullable<" + type.Argument + ">();");
          return;
        case TypeModelKind.List:
          w.Line("return " + Values + ".List<" + type.Argument + ">();");
          return;
        case TypeModelKind.Array:
          w.Line("return " + Values + ".Array<" + type.Argument + ">();");
          return;
        case TypeModelKind.HashSet:
          w.Line("return " + Values + ".HashSet<" + type.Argument + ">();");
          return;
        case TypeModelKind.Dictionary:
          w.Line("return " + Values + ".Dictionary<" + type.Argument + ">();");
          return;
        case TypeModelKind.CollectionInterface:
          w.Line("return " + Values + ".CollectionInterface<" + type.TypeName + ">();");
          return;
        case TypeModelKind.Collection when type.Factory != null:
          w.Line("return " + Values + ".Collection<" + type.TypeName + ", " + type.Argument + ">(items => " + type.Factory + "(items));");
          return;
        case TypeModelKind.Collection:
          w.Line("return " + Values + ".Collection<" + type.TypeName + ">(" + Creator(type) + ");");
          return;
        case TypeModelKind.Boxed:
          w.Line("return " + Values + ".Boxed<" + type.TypeName + ">();");
          return;
      }

      bool byRef = type.Kind == TypeModelKind.Struct;
      string factory = Values + (byRef ? ".Struct<" : ".Object<") + type.TypeName + ">(";
      string code = type.Members.Length > 0 ? "new " + CodeClass(index) + "()" : "null";
      if (type.Properties.Length == 0)
      {
        w.Line("return " + factory + Creator(type) + ", " + code + ");");
        return;
      }

      w.Line("return " + factory + Creator(type) + ", " + code + ",");
      w.Indent++;
      for (int t = 0; t < type.Properties.Length; t++)
      {
        PropertyModel property = type.Properties[t];
        string get, set;
        if (byRef) // the struct by reference (StructGetter, StructSetter): explicitly typed lambdas, C# 7.3 infers no ref parameters
        {
          get = property.CanGet ? "(ref " + type.TypeName + " o) => " + accessors.Get(type.TypeName, property.Name, property.TypeName, property.Access, property.UnsafeGet, "o", true) : "null";
          set = property.CanSet ? "(ref " + type.TypeName + " o, " + property.TypeName + " v) => " + accessors.Set(type.TypeName, property.Name, property.TypeName, property.Access, property.UnsafeSet, "o", "v", true) : "null";
        }
        else
        {
          get = property.CanGet ? "o => " + accessors.Get(type.TypeName, property.Name, property.TypeName, property.Access, property.UnsafeGet, "o", false) : "null";
          set = property.CanSet ? "(o, v) => " + accessors.Set(type.TypeName, property.Name, property.TypeName, property.Access, property.UnsafeSet, "o", "v", false) : "null";
        }
        w.Line(Values + (byRef ? ".StructProperty<" : ".Property<") + type.TypeName + ", " + property.TypeName + ">(\"" + property.Name + "\", " + get + ", " + set + ")" + (t < type.Properties.Length - 1 ? "," : ");"));
      }
      w.Indent--;
    }

    private static string DescriptionClass(int index)
    {
      return "LtMsgPackType" + index;
    }

    private static string CodeClass(int index)
    {
      return "LtMsgPackCode" + index;
    }

    private const string Generated = "global::LtMsgPack.Generated.";
    private const string Writing = "global::LtMsgPack.Writing.";
    private const string Reading = "global::LtMsgPack.Reading.";
    private const string IO = "global::LtMsgPack.IO.";

    /// <summary>
    /// The writer and reader of a class: the per property part of the runtime's ObjectPlan and ObjectReader, for the members of the kinds it writes and reads itself
    /// (the runtime does the others, and the ones its options write otherwise: see GeneratedWritePlan.Ids and PropReader.GeneratedId).
    /// A struct's is the same code on the struct by reference (GeneratedStructCode): <c>ref T o</c>, the runtime's writers and readers through the by reference helpers.
    /// </summary>
    private static void ObjectCode(CodeWriter w, TypeModel type, int index, Accessors accessors)
    {
      bool byRef = type.Kind == TypeModelKind.Struct;
      string t = (byRef ? "ref " : "") + type.TypeName; // the parameter's type
      string o = byRef ? "ref o" : "o"; // the argument
      w.Line("/// <summary>");
      w.Line("/// The generated writer and reader of " + type.TypeName.Replace("global::", "").Replace("<", "{").Replace(">", "}") + ".");
      w.Line("/// </summary>");
      w.Line("private sealed class " + CodeClass(index) + " : " + Generated + (byRef ? "GeneratedStructCode<" : "GeneratedObjectCode<") + type.TypeName + ">");
      w.Open();

      List<int> unrolled = new List<int>();
      for (int m = 0; m < type.Members.Length; m++)
        if (type.Members[m].Unrolled)
          unrolled.Add(m);

      w.Line("public " + CodeClass(index) + "() : base(new " + Generated + "GeneratedMember[]");
      w.Open();
      for (int m = 0; m < type.Members.Length; m++)
      {
        MemberModel member = type.Members[m];
        w.Line("new " + Generated + "GeneratedMember(typeof(" + member.DeclaringType + "), \"" + member.Name + "\", typeof(" + member.TypeName + "), " + Generated + "GeneratedKind." + member.Kind + ", "
          + Bool(member.Nullable) + ", " + Bool(member.CanGet) + ", " + Bool(member.CanSet) + ")" + (m < type.Members.Length - 1 ? "," : ""));
      }
      w.Indent--;
      bool isDefault = byRef && type.IsDefault != null;
      w.Line("}, new int[] { " + string.Join(", ", unrolled) + " }, " + Generated + "GeneratedCapabilities.Write | " + Generated + "GeneratedCapabilities.WriteUnrolled | "
        + Generated + "GeneratedCapabilities.ReadPositional | " + Generated + "GeneratedCapabilities.ReadPositionalNil | " + Generated + "GeneratedCapabilities.ReadMap"
        + (isDefault ? " | " + Generated + "GeneratedCapabilities.IsDefault" : "") + ")");
      w.Open();
      w.Close();

      if (isDefault) // FilterDefaultValues: the struct's fields against their defaults (LtMsgPack's StructDefault), without a box
      {
        w.Line();
        w.Line("public override bool IsDefault(ref " + type.TypeName + " v)");
        w.Open();
        w.Line("return " + type.IsDefault + ";");
        w.Close();
      }

      // Write: the values in the runtime's order (p.Ids), map entries with keys, array items without
      w.Line();
      w.Line("public override int Write(" + Writing + "WriteContext c, " + t + " o, byte[][] keys, global::LsMsgPack.Meta.FullPropertyInfo[] infos, " + Generated + "GeneratedWritePlan p, out int end)");
      w.Open();
      w.Line(IO + "MsgPackWriter w = c.W;");
      w.Line("int[] ids = p.Ids;");
      w.Line("bool filter = p.FilterDefaults;");
      w.Line("bool trim = p.Trim && keys == null;");
      w.Line("int count = 0;");
      w.Line("int last = 0;");
      w.Line("end = w.Pos;");
      w.Line("for (int t = 0; t < ids.Length; t++)");
      w.Open();
      w.Line("byte[] key = keys == null ? null : keys[t];");
      w.Line("int start = w.Pos;");
      w.Line("bool written;");
      w.Line("switch (ids[t])");
      w.Open();
      for (int m = 0; m < type.Members.Length; m++)
      {
        MemberModel member = type.Members[m];
        if (member.Kind == "None" || !member.CanGet)
          continue;
        w.Line("case " + m + ":");
        w.Open();
        w.Line(member.TypeName + " v = " + Get(accessors, member) + ";");
        w.Line("if (filter && " + Omitted(member, "v") + ")");
        w.Open();
        w.Line("written = false;");
        w.Line("break;");
        w.Close();
        w.Line("if (key != null)");
        w.Line("  w.Raw(key);");
        WriteValue(w, member, "v");
        w.Line("written = true;");
        w.Line("break;");
        w.Close();
      }
      w.Line("default:");
      w.Line("  written = p.Runtime(t, c, " + o + ", key, infos[t]);");
      w.Line("  break;");
      w.Close();
      w.Line("if (written)");
      w.Line("  count++;");
      w.Line("else if (key == null)");
      w.Line("  w.Nil(); // the array layout: nil for a value the filters leave out");
      w.Line("if (trim && (w.Pos != start + 1 || w.Buf[start] != 0xC0)) // nil is the only value of one byte 0xC0");
      w.Open();
      w.Line("last = t + 1;");
      w.Line("end = w.Pos;");
      w.Close();
      w.Close();
      w.Line("return trim ? last : count;");
      w.Close();

      // WriteUnrolled: the array layout when the runtime's properties are the unrolled ones
      w.Line();
      w.Line("public override void WriteUnrolled(" + Writing + "WriteContext c, " + t + " o, global::LsMsgPack.Meta.FullPropertyInfo[] infos, " + Generated + "GeneratedWritePlan p)");
      w.Open();
      w.Line(IO + "MsgPackWriter w = c.W;");
      w.Line("bool filter = p.FilterDefaults;");
      for (int position = 0; position < unrolled.Count; position++)
      {
        MemberModel member = type.Members[unrolled[position]];
        if (member.Kind == "None" || !member.CanGet)
        {
          w.Line("if (!p.Runtime(" + position + ", c, " + o + ", null, infos[" + position + "]))");
          w.Line("  w.Nil();");
          continue;
        }
        w.Open();
        w.Line(member.TypeName + " v = " + Get(accessors, member) + ";");
        w.Line("if (filter && " + Omitted(member, "v") + ")");
        w.Line("  w.Nil();");
        w.Line("else");
        w.Open();
        WriteValue(w, member, "v");
        w.Close();
        w.Close();
      }
      w.Close();

      // ReadPositional: the array layout (ObjectReader.ReadPositional's loop)
      w.Line();
      w.Line("public override void ReadPositional(" + Reading + "ReadContext c, " + t + " o, " + Reading + "PropReader[] props, int items, " + Generated + "GeneratedReadPlan p)");
      w.Open();
      w.Line(IO + "MsgPackReader r = c.R;");
      w.Line("for (int t = 0; t < items; t++)");
      w.Open();
      w.Line(Reading + "PropReader prop = t < props.Length ? props[t] : null;");
      w.Line("if (prop == null)");
      w.Open();
      w.Line("r.Skip(c.Depth); // not a property of this type (added by a newer writer, or ignored here)");
      w.Line("continue;");
      w.Close();
      w.Line("if (r.TryReadNil())");
      w.Open();
      // The value the writer leaves out: without [DefaultValue] the default of the type, whatever the options are (FullPropertyInfo.NilValue)
      bool direct = false;
      for (int m = 0; m < type.Members.Length; m++)
        direct |= IsReadHere(type.Members[m]) && !type.Members[m].HasDefaultValue;
      if (direct)
      {
        w.Line("switch (prop.GeneratedId)");
        w.Open();
        for (int m = 0; m < type.Members.Length; m++)
        {
          MemberModel member = type.Members[m];
          if (!IsReadHere(member) || member.HasDefaultValue)
            continue;
          w.Line("case " + m + ":");
          w.Line("  " + Set(accessors, member, "default(" + member.TypeName + ")") + ";");
          w.Line("  continue;");
        }
        w.Close();
      }
      w.Line((byRef ? Generated + "GeneratedIO.ReadNil(prop, ref o);" : "prop.ReadNil(o);") + " // the value the writer leaves out (null, the default of the type or of [DefaultValue])");
      w.Line("continue;");
      w.Close();
      bool reads = ReadsAny(type); // no empty switch (warning CS1522)
      if (reads)
      {
        w.Line("switch (prop.GeneratedId)");
        w.Open();
      }
      for (int m = 0; m < type.Members.Length; m++)
      {
        MemberModel member = type.Members[m];
        if (member.Kind == "None" || !member.CanSet)
          continue;
        w.Line("case " + m + ":");
        w.Open();
        ReadValue(w, member, "continue;", accessors);
        w.Line("break;");
        w.Close();
      }
      if (reads)
        w.Close();
      w.Line((byRef ? Generated + "GeneratedIO.Read(prop, c, ref o);" : "prop.Read(c, o);") + " // another format: read as the runtime does");
      w.Close();
      w.Close();

      // ReadMap: the map layout (ObjectReader.Read's loop). The loop is here, as in ReadPositional: this method has the code of every property, and the JIT zeroes its frame per call
      w.Line();
      w.Line("public override bool ReadMap(" + Reading + "ReadContext c, " + t + " o, " + Reading + "ReadPlan plan, " + Reading + "PropReader[] bound, int count, " + Generated + "GeneratedReadPlan p)");
      w.Open();
      w.Line(IO + "MsgPackReader r = c.R;");
      w.Line("int next = 0;");
      w.Line("for (int t = 0; t < count; t++)");
      w.Open();
      w.Line(Reading + "PropReader prop;");
      w.Line("if (!" + Generated + "GeneratedIO.TryReadKey(c, plan, bound, ref next, out prop))");
      w.Line("  return false;");
      w.Line("if (prop == null)");
      w.Open();
      w.Line("r.Skip(c.Depth); // not a property of this type (removed, or ignored here)");
      w.Line("continue;");
      w.Close();
      if (reads)
      {
        w.Line("switch (prop.GeneratedId)");
        w.Open();
      }
      for (int m = 0; m < type.Members.Length; m++)
      {
        MemberModel member = type.Members[m];
        if (member.Kind == "None" || !member.CanSet)
          continue;
        w.Line("case " + m + ":");
        w.Open();
        if (member.Nullable)
        {
          w.Line("if (r.TryReadNil())");
          w.Open();
          w.Line(Set(accessors, member, "null") + ";");
          w.Line("continue;");
          w.Close();
          ReadValue(w, member, "continue;", accessors);
        }
        else
        {
          ReadValue(w, member, "continue;", accessors);
          w.Line("if (r.TryReadNil())");
          w.Open();
          w.Line(Set(accessors, member, "default(" + member.TypeName + ")") + ";");
          w.Line("continue;");
          w.Close();
        }
        w.Line("break;");
        w.Close();
      }
      if (reads)
        w.Close();
      w.Line((byRef ? Generated + "GeneratedIO.Read(prop, c, ref o);" : "prop.Read(c, o);") + " // another format: read as the runtime does");
      w.Close();
      w.Line("return true;");
      w.Close();

      w.Close();
    }

    /// <summary>
    /// Whether the generated code reads any member of the type itself (otherwise the runtime reads them all).
    /// </summary>
    private static bool ReadsAny(TypeModel type)
    {
      for (int m = 0; m < type.Members.Length; m++)
        if (IsReadHere(type.Members[m]))
          return true;
      return false;
    }

    /// <summary>
    /// The generated code reads the member (otherwise the runtime does).
    /// </summary>
    private static bool IsReadHere(MemberModel member)
    {
      return member.Kind != "None" && member.CanSet;
    }

    private static string Bool(bool value)
    {
      return value ? "true" : "false";
    }

    /// <summary>
    /// FilterDefaultValues for the member's value (as the runtime's handlers decide it: ValueHandler.IncludeByDefault).
    /// </summary>
    private static string Omitted(MemberModel member, string v)
    {
      if (member.Nullable)
        return "!" + v + ".HasValue";
      switch (member.Kind)
      {
        case "String": return v + " == null"; // an empty string is not a default value
        case "Boolean": return "!" + v;
        case "Char": return v + " == '\\0'";
        case "Decimal": return Generated + "GeneratedIO.IsZero(" + v + ")";
        case "Guid": return v + " == global::System.Guid.Empty";
        case "DateTime":
        case "TimeSpan": return v + ".Ticks == 0"; // DateTime.Equals ignores the Kind
        default: return v + " == 0"; // numbers and enums
      }
    }

    /// <summary>
    /// The value as the runtime's handler of its type writes it.
    /// </summary>
    private static void WriteValue(CodeWriter w, MemberModel member, string v)
    {
      if (member.Nullable)
      {
        w.Line("if (" + v + ".HasValue)");
        w.Open();
        w.Line(member.ValueType + " u = " + v + ".GetValueOrDefault();");
        WriteValue(w, member with { Nullable = false }, "u");
        w.Close();
        w.Line("else");
        w.Line("  w.Nil();");
        return;
      }

      switch (member.Kind)
      {
        case "String":
          w.Line("if (" + v + " == null)");
          w.Line("  w.Nil();");
          w.Line("else");
          w.Line("  w.String(" + v + ");");
          return;
        case "Boolean": w.Line("w.Bool(" + v + ");"); return;
        case "SByte": w.Line("w.SByte(" + v + ");"); return;
        case "Int16": w.Line("w.Int16(" + v + ");"); return;
        case "Int32": w.Line("w.Int32(" + v + ");"); return;
        case "Int64": w.Line("w.Int64(" + v + ");"); return;
        case "Byte": w.Line("w.UInt8(" + v + ");"); return;
        case "UInt16": w.Line("w.UInt16(" + v + ");"); return;
        case "UInt32": w.Line("w.UInt32(" + v + ");"); return;
        case "UInt64": w.Line("w.UInt64(" + v + ");"); return;
        case "Single": w.Line("w.Single(" + v + ");"); return;
        case "Double": w.Line("w.Double(" + v + ");"); return;
        case "Char": w.Line("w.UInt16(" + v + ");"); return; // as an unsigned 16 bit integer, like MessagePack-CSharp
        case "Decimal": w.Line(Generated + "GeneratedIO.WriteDecimal(w, " + v + ", p.DecimalCode);"); return;
        case "Guid": w.Line("w.Guid(" + v + ");"); return;
        case "DateTime": w.Line("w.DateTime(" + Generated + "GeneratedIO.Utc(" + v + ", p));"); return;
        case "TimeSpan": w.Line("w.Int64(" + v + ".Ticks);"); return;
        case "Enum": w.Line("w." + EnumWriter(member.EnumUnderlying) + "((" + member.EnumUnderlying + ")" + v + ");"); return;
      }
      throw new System.InvalidOperationException("Unknown kind " + member.Kind);
    }

    private static string EnumWriter(string underlying)
    {
      switch (underlying)
      {
        case "sbyte": return "SByte";
        case "short": return "Int16";
        case "int": return "Int32";
        case "long": return "Int64";
        case "byte": return "UInt8";
        case "ushort": return "UInt16";
        case "uint": return "UInt32";
        default: return "UInt64";
      }
    }

    /// <summary>
    /// Reads the value when it is in the format the runtime's reader of its type reads directly (then <paramref name="done"/>), otherwise leaves the position where it was.
    /// </summary>
    private static void ReadValue(CodeWriter w, MemberModel member, string done, Accessors accessors)
    {
      string set = Set(accessors, member, "v") + ";";
      switch (member.Kind)
      {
        case "String": Fast(w, "r.TryReadString(out string v)", set, done); return;
        case "Boolean": Fast(w, "r.TryReadBool(out bool v)", set, done); return;
        case "Single": Fast(w, "r.TryReadSingle(out float v)", set, done); return;
        case "Double": Fast(w, "r.TryReadDouble(out double v)", set, done); return;
        case "Int64": Fast(w, "r.TryReadInt64(out long v)", set, done); return;
        case "UInt64": Fast(w, "r.TryReadUInt64(out ulong v)", set, done); return;
        case "SByte": Ranged(w, "sbyte", "sbyte.MinValue", "sbyte.MaxValue", accessors, member, done); return;
        case "Int16": Ranged(w, "short", "short.MinValue", "short.MaxValue", accessors, member, done); return;
        case "Int32": Ranged(w, "int", "int.MinValue", "int.MaxValue", accessors, member, done); return;
        case "Byte": Ranged(w, "byte", "byte.MinValue", "byte.MaxValue", accessors, member, done); return;
        case "UInt16": Ranged(w, "ushort", "ushort.MinValue", "ushort.MaxValue", accessors, member, done); return;
        case "UInt32": Ranged(w, "uint", "uint.MinValue", "uint.MaxValue", accessors, member, done); return;
        case "Char": Ranged(w, "char", "char.MinValue", "char.MaxValue", accessors, member, done); return;
        case "Decimal": Fast(w, Generated + "GeneratedIO.TryReadDecimal(r, p.DecimalCode, out decimal v)", set, done); return;
        case "Guid": Fast(w, "r.TryReadGuid(out global::System.Guid v)", set, done); return;
        case "DateTime": Fast(w, "r.TryReadDateTime(out global::System.DateTime v)", set, done); return;
        case "TimeSpan": Fast(w, "r.TryReadInt64(out long v)", Set(accessors, member, "new global::System.TimeSpan(v)") + ";", done); return;
        case "Enum": Fast(w, "r.TryReadInt64(out long v)", Set(accessors, member, "(" + member.ValueType + ")unchecked((" + member.EnumUnderlying + ")v)") + ";", done); return; // values out of range wrap around (EnumReader)
      }
      throw new System.InvalidOperationException("Unknown kind " + member.Kind);
    }

    private static void Fast(CodeWriter w, string condition, string set, string done)
    {
      w.Line("if (" + condition + ")");
      w.Open();
      w.Line(set);
      w.Line(done);
      w.Close();
    }

    /// <summary>
    /// An integer read as long and checked (IntegerReader): out of range the position is restored, the runtime throws the overflow as it does.
    /// </summary>
    private static void Ranged(CodeWriter w, string type, string min, string max, Accessors accessors, MemberModel member, string done)
    {
      w.Line("int start = r.Pos;");
      w.Line("if (r.TryReadInt64(out long v))");
      w.Open();
      w.Line("if (v >= " + min + " && v <= " + max + ")");
      w.Open();
      w.Line(Set(accessors, member, "(" + type + ")v") + ";");
      w.Line(done);
      w.Close();
      w.Line("r.Pos = start;");
      w.Close();
    }

    /// <summary>
    /// The value of the member of <c>o</c> (an expression).
    /// </summary>
    private static string Get(Accessors accessors, MemberModel member)
    {
      return accessors.Get(member.DeclaringType, member.Name, member.TypeName, member.Access, member.UnsafeGet, "o", member.ByRef);
    }

    /// <summary>
    /// Sets the member of <c>o</c> to the value (a statement without its semicolon).
    /// </summary>
    private static string Set(Accessors accessors, MemberModel member, string value)
    {
      return accessors.Set(member.DeclaringType, member.Name, member.TypeName, member.Access, member.UnsafeSet, "o", value, member.ByRef);
    }

    /// <summary>
    /// The UnsafeAccessor methods of a context (.NET 8): the non-public getters and setters and the init-only setters the generated code calls, declared once per property (written by <see cref="Write"/> at the end of the context class,
    /// the generated writers and readers are nested in it).
    /// </summary>
    private sealed class Accessors
    {
      private readonly Dictionary<string, string> _names = new Dictionary<string, string>();
      private readonly List<string> _declarations = new List<string>();

      /// <param name="byRef">A struct: <paramref name="target"/> is a ref parameter, the accessor takes it by reference</param>
      /// <returns>The value of the property of <paramref name="target"/> (an expression)</returns>
      public string Get(string declaringType, string name, string typeName, string access, bool viaAccessor, string target, bool byRef)
      {
        if (!viaAccessor)
          return target + "." + access;
        return Method(declaringType, name, typeName, true, byRef) + "(" + (byRef ? "ref " : "") + target + ")";
      }

      /// <returns>The assignment of the property of <paramref name="target"/> (a statement without its semicolon, or a lambda body)</returns>
      public string Set(string declaringType, string name, string typeName, string access, bool viaAccessor, string target, string value, bool byRef)
      {
        if (!viaAccessor)
          return target + "." + access + " = " + value;
        return Method(declaringType, name, typeName, false, byRef) + "(" + (byRef ? "ref " : "") + target + ", " + value + ")";
      }

      /// <param name="byRef">A struct: UnsafeAccessor takes the instance of a value type by reference</param>
      private string Method(string declaringType, string name, string typeName, bool get, bool byRef)
      {
        string self = (byRef ? "ref " : "") + declaringType + " o";
        string key = (get ? "get " : "set ") + declaringType + " " + name;
        if (_names.TryGetValue(key, out string method))
          return method;
        method = (get ? "LtMsgPackGet" : "LtMsgPackSet") + _names.Count;
        _names.Add(key, method);
        string accessor = "[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = \"" + (get ? "get_" : "set_") + name + "\")]";
        _declarations.Add(accessor);
        _declarations.Add(get
          ? "private static extern " + typeName + " " + method + "(" + self + ");"
          : "private static extern void " + method + "(" + self + ", " + typeName + " value);");
        return method;
      }

      public void Write(CodeWriter w)
      {
        if (_declarations.Count == 0)
          return;
        w.Line();
        w.Line("// The init-only setters, and the non-public accessors of properties the runtime may serialize (FilterNonSettable's NonPublicProperties)");
        foreach (string line in _declarations)
          w.Line(line);
      }
    }

    private static string Creator(TypeModel type)
    {
      return type.HasCreator ? "() => new " + type.TypeName + "()" : "null";
    }

    private static string Registration(List<ContextModel> contexts, GenerateOptions options)
    {
      CodeWriter w = new CodeWriter();
      w.Line("// <auto-generated/>");
      w.Line("// Written by LtMsgPack's source generator: registers the contexts of this assembly for the process (LtMsgPackGenerate.AutoRegister, LtMsgPackAutoRegister).");
      w.Line("#pragma warning disable CA2255 // a module initializer in a library: registering is its purpose");
      w.Line();
      w.Line("internal static class LtMsgPackGeneratedRegistration");
      w.Open();
      w.Line("[global::System.Runtime.CompilerServices.ModuleInitializer]");
      w.Line("internal static void Register()");
      w.Open();
      foreach (ContextModel context in contexts)
        w.Line("global::LsMsgPack.Generated.GeneratedTypes.Register(" + context.FullName + ".Default);");
      w.Close();
      w.Close();

      if (!options.HasModuleInitializerAttribute) // .NET Standard and .NET Framework: the compiler recognizes the attribute by its name
      {
        w.Line();
        w.Line("namespace System.Runtime.CompilerServices");
        w.Open();
        w.Line("[global::System.AttributeUsage(global::System.AttributeTargets.Method, Inherited = false)]");
        w.Line("internal sealed class ModuleInitializerAttribute : global::System.Attribute");
        w.Open();
        w.Close();
        w.Close();
      }
      return w.ToString();
    }

    private sealed class CodeWriter
    {
      private readonly StringBuilder _text = new StringBuilder();
      public int Indent;

      public void Line(string line = "")
      {
        if (line.Length > 0)
          _text.Append(' ', Indent * 2);
        _text.Append(line).Append('\n');
      }

      public void Open()
      {
        Line("{");
        Indent++;
      }

      public void Close()
      {
        Indent--;
        Line("}");
      }

      public override string ToString() => _text.ToString();
    }
  }
