using LsMsgPack;
using LtMsgPack.Http;
using System;
using System.Collections.Generic;
using System.Text;

namespace LsMsgPackTypeScript
{
  /// <summary>
  /// Writes the hot-load schema set: the schemas the server will write for the response types (version 2, as the client asks for them), made by the server's own code
  /// (<see cref="LtMsgPackHttpSerializer.PrepareSchema"/> with the server's options and <see cref="MsgPackOptions.CompleteSchemas"/>), so they have the ids the server's responses refer to.
  /// The client holds them from the start: the first response of each type is a reference (18 bytes) instead of the schema.
  /// </summary>
  internal static class SchemaSetWriter
  {
    internal sealed class Prepared
    {
      internal Type Root;
      internal SchemaId Id;
      internal byte[] Bytes;
    }

    /// <summary>
    /// The schemas of the roots (a root without classes has none: nothing to hold).
    /// </summary>
    internal static List<Prepared> Prepare(LtMsgPackHttpOptions options, IEnumerable<Type> roots, List<string> warnings)
    {
      List<Prepared> prepared = new List<Prepared>();
      LtMsgPackHttpSerializer serializer = new LtMsgPackHttpSerializer(options);
      if (!serializer.NegotiatesSchemas || !serializer.DescribesSchemas || !options.CompleteSchemas)
      {
        warnings.Add("The server's options do not negotiate complete schemas of version 2 (NegotiateSchemas, DescribeSchemas, CompleteSchemas and the indexed schema): no schema set is written.");
        return prepared;
      }
      HashSet<SchemaId> seen = new HashSet<SchemaId>();
      foreach (Type root in roots)
      {
        SchemaId id = serializer.PrepareSchema(root, true);
        byte[] bytes = serializer.SchemaStore.GetSchema(id);
        if (bytes is null || SchemaBytes.Parse(bytes, null, out SchemaVersion _).Count == 0 || !seen.Add(id)) // only the root entry: no classes, nothing to hold
          continue;
        prepared.Add(new Prepared() { Root = root, Id = id, Bytes = bytes });
      }
      return prepared;
    }

    internal static string Write(List<Prepared> schemas, string source)
    {
      StringBuilder sb = new StringBuilder();
      sb.Append("// Generated by lsmsgpack-ts ").Append(GeneratorOptions.Version).Append(" from ").Append(source).Append(": the schemas the server writes for these response types (application/x-lsmsgpack, version 2).\n");
      sb.Append("// Give them to the client (new LsMsgPackClient({ schemas })), it then holds them from the start. A server with other classes or options writes other schemas: those come inline as usual.\n");
      sb.Append("/* eslint-disable */\n");
      sb.Append("export const schemas: Readonly<Record<string, string>> = {\n");
      foreach (Prepared schema in schemas)
      {
        sb.Append("  // ").Append(schema.Id.ToString()).Append(", ").Append(schema.Bytes.Length).Append(" bytes\n");
        sb.Append("  ").Append(Defaults.Quote(TypeName(schema.Root))).Append(": ").Append(Defaults.Quote(Convert.ToBase64String(schema.Bytes))).Append(",\n");
      }
      sb.Append("};\n");
      return sb.ToString();
    }

    /// <summary>
    /// The root as C# writes it (Shop.Invoice[], System.Collections.Generic.List&lt;Shop.Invoice&gt;), only for the reader of the file.
    /// </summary>
    internal static string TypeName(Type type)
    {
      if (type.IsArray)
        return string.Concat(TypeName(type.GetElementType()), "[", new string(',', type.GetArrayRank() - 1), "]");
      if (!type.IsGenericType)
        return (type.FullName ?? type.Name).Replace('+', '.');
      string name = type.GetGenericTypeDefinition().FullName ?? type.Name;
      name = name.Substring(0, name.IndexOf('`')).Replace('+', '.');
      List<string> args = new List<string>();
      foreach (Type arg in type.GetGenericArguments())
        args.Add(TypeName(arg));
      return string.Concat(name, "<", string.Join(", ", args), ">");
    }
  }
}
