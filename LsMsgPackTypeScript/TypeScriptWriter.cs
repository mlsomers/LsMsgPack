using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;

namespace LsMsgPackTypeScript
{
  /// <summary>
  /// Writes the models file: a const object and type per enum, an interface per .NET interface, a class per .NET class and struct (base classes first, with <c>extends</c>)
  /// whose fields have the values the constructor sets, and <c>defineModels(...)</c> with the type name and the declared types of the properties of each class
  /// (in the form of the described schema, docs/schema.md "Version 2", with <c>['class', name]</c> and <c>['struct', name]</c> instead of entry indexes) for the client.
  /// </summary>
  internal sealed class TypeScriptWriter
  {
    private readonly ModelSet _models;
    private readonly GeneratorOptions _options;
    private readonly Defaults _defaults;
    private readonly StringBuilder _sb = new StringBuilder();

    internal TypeScriptWriter(ModelSet models, GeneratorOptions options, Defaults defaults)
    {
      _models = models;
      _options = options;
      _defaults = defaults;
    }

    private static readonly HashSet<string> Reserved = new HashSet<string>(StringComparer.Ordinal)
    {
      "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum", "export", "extends", "false", "finally", "for", "function", "if", "import", "in",
      "instanceof", "new", "null", "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "implements", "interface", "let", "package", "private",
      "protected", "public", "static", "yield", "any", "boolean", "number", "string", "symbol", "bigint", "unknown", "never", "object", "type", "Date", "Uint8Array", "Record", "Object", "Array",
      "defineModels", "models",
    };

    internal static bool IsReserved(string name)
    {
      return Reserved.Contains(name);
    }

    /// <summary>
    /// A property name as a key of a class or object literal: the name when it is an identifier, otherwise quoted.
    /// </summary>
    internal static string PropertyKey(string name)
    {
      return IsIdentifier(name) ? name : Defaults.Quote(name);
    }

    internal static string Member(string name)
    {
      return PropertyKey(name);
    }

    private static bool IsIdentifier(string name)
    {
      if (string.IsNullOrEmpty(name) || !(char.IsLetter(name[0]) || name[0] == '_' || name[0] == '$'))
        return false;
      for (int t = 1; t < name.Length; t++)
        if (!(char.IsLetterOrDigit(name[t]) || name[t] == '_' || name[t] == '$'))
          return false;
      return true;
    }

    internal string Write(string source)
    {
      _sb.Append("// Generated by lsmsgpack-ts ").Append(GeneratorOptions.Version).Append(" from ").Append(source).Append(": the .NET model classes for @lsmsgpack/client.\n");
      _sb.Append("// Do not edit, run lsmsgpack-ts again when the classes change. Fields start with the values the .NET constructors set.\n");
      _sb.Append("// Read with the options int64: '").Append(_options.Int64).Append("', dates: '").Append(_options.Dates).Append("', decimal: '").Append(_options.Decimal);
      _sb.Append("', propertyNames: '").Append(_options.PropertyNames).Append("' (the client checks them).\n");
      _sb.Append("/* eslint-disable */\n");
      _sb.Append("import { defineModels } from '").Append(_options.Import).Append("';\n");

      foreach (Type type in _models.Enums)
        WriteEnum(type);
      foreach (ModelInterface model in _models.Interfaces)
        WriteInterface(model);
      List<ModelClass> classes = _models.Classes;
      foreach (ModelClass model in classes)
        WriteClass(model, classes);
      WriteRegistry(classes);
      return _sb.ToString();
    }

    private void WriteEnum(Type type)
    {
      string name = _models.EnumName(type);
      bool int64 = Enum.GetUnderlyingType(type) == typeof(long) || Enum.GetUnderlyingType(type) == typeof(ulong);
      string suffix = int64 && _options.Int64 == "bigint" ? "n" : string.Empty;
      _sb.Append("\n/** .NET ").Append(type.FullName).Append(" */\n");
      _sb.Append("export const ").Append(name).Append(" = {\n");
      foreach (string member in Enum.GetNames(type))
      {
        object underlying = Convert.ChangeType(Enum.Parse(type, member), Enum.GetUnderlyingType(type), CultureInfo.InvariantCulture);
        _sb.Append("  ").Append(PropertyKey(member)).Append(": ").Append(Convert.ToString(underlying, CultureInfo.InvariantCulture)).Append(suffix).Append(",\n");
      }
      _sb.Append("} as const;\n");
      if (type.IsDefined(typeof(FlagsAttribute), false))
        _sb.Append("export type ").Append(name).Append(" = ").Append(int64 && _options.Int64 == "bigint" ? "bigint" : "number").Append("; // [Flags]: combinations of the values\n");
      else
        _sb.Append("export type ").Append(name).Append(" = (typeof ").Append(name).Append(")[keyof typeof ").Append(name).Append("];\n");
    }

    private void WriteInterface(ModelInterface model)
    {
      _sb.Append("\n/** .NET ").Append(model.Type.FullName).Append(" (its classes have these properties when they write them) */\n");
      _sb.Append("export interface ").Append(model.TsName).Append(" {\n");
      _sb.Append("  readonly $type: string;\n");
      foreach (ModelProperty prop in model.Props)
        _sb.Append("  readonly ").Append(PropertyKey(_options.Field(prop.Name))).Append("?: ").Append(TsType(_models.SpecOf(prop.Type), prop.Nullability, true)).Append(";\n");
      _sb.Append("}\n");
    }

    private void WriteClass(ModelClass model, List<ModelClass> all)
    {
      _sb.Append("\n/** .NET ").Append(model.Type.FullName).Append(" */\n");
      _sb.Append("export ").Append(model.IsAbstract ? "abstract " : string.Empty).Append("class ").Append(model.TsName);
      if (model.Base != null)
        _sb.Append(" extends ").Append(model.Base.TsName);
      _sb.Append(" {\n");

      List<string> names = all.Where(c => !c.IsAbstract && IsSelfOrDerived(c, model)).Select(c => Defaults.Quote(c.TypeName)).ToList();
      _sb.Append("  declare readonly $type: ").Append(names.Count == 0 ? "string" : string.Join(" | ", names)).Append(";\n");

      ThrowIfFieldsCollide(model);
      Dictionary<string, string> values = _defaults.Of(model);
      Dictionary<string, string> inherited = model.Base is null ? null : _defaults.Of(model.Base);
      foreach (ModelProperty prop in model.AllProps)
      {
        bool own = model.OwnProps.Contains(prop);
        if (!own && (inherited is null || !inherited.TryGetValue(prop.Name, out string baseValue) || string.Equals(baseValue, values[prop.Name], StringComparison.Ordinal)))
          continue; // the base class initializes it the same way
        string field = _options.Field(prop.Name);
        if (field == "constructor")
          continue; // not a field name a class can have
        string value = values[prop.Name];
        string type = TsType(_models.SpecOf(prop.Type), prop.Nullability, true);
        if (value == "null" && !type.EndsWith(" | null", StringComparison.Ordinal) && type != "unknown")
          type += " | null"; // declared not nullable, but nothing sets it
        _sb.Append("  ").Append(own ? string.Empty : "override ").Append(PropertyKey(field)).Append(": ").Append(type).Append(" = ").Append(value).Append(";\n");
      }
      _sb.Append("}\n");
    }

    /// <summary>
    /// Two properties with the same field name (Id and ID with camelCase): System.Text.Json refuses them too.
    /// </summary>
    private void ThrowIfFieldsCollide(ModelClass model)
    {
      foreach (IGrouping<string, ModelProperty> same in model.AllProps.GroupBy(p => _options.Field(p.Name), StringComparer.Ordinal).Where(g => g.Count() > 1))
        throw new UsageException(string.Concat(model.Type.FullName, ": the properties ", string.Join(" and ", same.Select(p => p.Name)), " have the same field name ", same.Key,
          " with --property-names ", _options.PropertyNames, "."));
    }

    private static bool IsSelfOrDerived(ModelClass candidate, ModelClass model)
    {
      for (ModelClass c = candidate; c != null; c = c.Base)
        if (c == model)
          return true;
      return false;
    }

    private void WriteRegistry(List<ModelClass> classes)
    {
      _sb.Append("\n/** The models for the client: new LsMsgPackClient({ models }). */\n");
      _sb.Append("export const models = defineModels({\n");
      _sb.Append("  generator: ").Append(Defaults.Quote("lsmsgpack-ts " + GeneratorOptions.Version)).Append(",\n");
      _sb.Append("  int64: '").Append(_options.Int64).Append("',\n");
      _sb.Append("  dates: '").Append(_options.Dates).Append("',\n");
      _sb.Append("  decimal: '").Append(_options.Decimal).Append("',\n");
      // always written: released clients and defineModels read a file without it as 'dotnet' (the generator's default in 2026.10.22)
      _sb.Append("  propertyNames: '").Append(_options.PropertyNames).Append("',\n");
      _sb.Append("  classes: [\n");
      foreach (ModelClass model in classes.Where(c => !c.IsAbstract))
      {
        _sb.Append("    [").Append(model.TsName).Append(", ").Append(Defaults.Quote(model.TypeName)).Append(", [");
        _sb.Append(string.Join(", ", model.AllProps.Select(p => string.Concat("[", Defaults.Quote(p.Name), ", ", SpecText(_models.SpecOf(p.Type)), "]"))));
        _sb.Append("]],\n");
      }
      _sb.Append("  ],\n");
      _sb.Append("});\n");
    }

    /// <summary>
    /// The declared type for the client (the form of the described schema, classes by their type name).
    /// </summary>
    private static string SpecText(Spec spec)
    {
      switch (spec.Name)
      {
        case "class":
        case "struct":
          return string.Concat("['", spec.Name, "', ", Defaults.Quote(spec.Class.TypeName), "]");
        case "?":
        case "list":
        case "dict":
        case "pair":
        case "tuple":
          return string.Concat("['", spec.Name, "', ", string.Join(", ", spec.Items.Select(SpecText)), "]");
      }
      return Defaults.Quote(spec.Name);
    }

    /// <summary>
    /// The TypeScript type of a value as the client reads it with the options. A reference type can be null unless its nullable annotation says it cannot;
    /// without annotations the values of a property can be null, the elements of collections and values of dictionaries are taken as not null (what JSON clients usually declare).
    /// </summary>
    /// <param name="nullability">The annotations of the value, null when unknown</param>
    /// <param name="top">A property (not an element)</param>
    internal string TsType(Spec spec, NullabilityInfo nullability, bool top)
    {
      string type;
      switch (spec.Name)
      {
        case "?":
          string inner = TsType(spec.Items[0], null, false);
          return inner.EndsWith(" | null", StringComparison.Ordinal) ? inner : inner + " | null";
        case "bool": return "boolean";
        case "int":
        case "float":
          return spec.Enum != null && _models.Enums.Contains(spec.Enum) ? _models.EnumName(spec.Enum) : "number";
        case "long":
        case "ulong":
          return spec.Enum != null && _models.Enums.Contains(spec.Enum) ? _models.EnumName(spec.Enum) : _options.Int64 == "bigint" ? "bigint" : "number";
        case "bigint": return "bigint";
        case "decimal": return _options.Decimal == "string" ? "string" : "number";
        case "char":
        case "guid":
        case "timespan":
        case "dateonly":
        case "timeonly":
          return "string";
        case "datetime":
        case "dto":
        case "dto-clock":
          return _options.Dates == "iso" ? "string" : "Date";
        case "pair": return string.Concat("{ ", _options.Field("Key"), ": ", TsType(spec.Items[0], Argument(nullability, 0), true), "; ", _options.Field("Value"), ": ", TsType(spec.Items[1], Argument(nullability, 1), true), " }"); // a default pair has null in both
        case "struct": return spec.Class.TsName;
        case "string":
        case "uri":
          type = "string";
          break;
        case "bin":
          type = "Uint8Array";
          break;
        case "list":
          type = string.Concat(Element(TsType(spec.Items[0], ElementOf(spec, nullability), false)), "[]");
          break;
        case "dict":
          type = string.Concat("Record<string, ", TsType(spec.Items[1], spec.Type.IsGenericType && spec.Type.GetGenericArguments().Length == 2 ? Argument(nullability, 1) : null, false), ">");
          break;
        case "tuple":
          type = string.Concat("[", string.Join(", ", spec.Items.Select((item, t) => TsType(item, Argument(nullability, t), false))), "]");
          break;
        case "class":
          type = spec.Class.TsName;
          break;
        default:
          if (spec.Interface is null)
            return "unknown";
          type = spec.Interface.TsName;
          break;
      }
      NullabilityState state = nullability?.ReadState ?? NullabilityState.Unknown;
      return state == NullabilityState.Nullable || (state == NullabilityState.Unknown && top) ? type + " | null" : type;
    }

    private static NullabilityInfo ElementOf(Spec list, NullabilityInfo nullability)
    {
      if (nullability is null)
        return null;
      if (list.Type.IsArray)
        return nullability.ElementType;
      return list.Type.IsGenericType && nullability.GenericTypeArguments.Length == 1 ? nullability.GenericTypeArguments[0] : null;
    }

    private static NullabilityInfo Argument(NullabilityInfo nullability, int index)
    {
      return nullability != null && index < nullability.GenericTypeArguments.Length ? nullability.GenericTypeArguments[index] : null;
    }

    private static string Element(string type)
    {
      return type.IndexOf(' ') >= 0 ? string.Concat("(", type, ")") : type;
    }
  }
}
