#!/usr/bin/env python3
# Writes the 200 vertical slices of WebMany.cs to stdout: a backend in the Vertical Slice Architecture, each feature its own static class with nested
# Request/Response (and Item/Line/Row) classes, so 200 classes named Response, a few shared kernel types (Money, PostalAddress), its handler,
# a minimal API endpoint (/s/<area>/<verb>-<entity>-<letters>) and an MVC controller (/m/... the same path): names without digits, as real routes have them
# (a client may take segments of digits for ids). Even slices are queries (GET .../{id}), odd ones commands (POST with a Request body).
# About 1 in 8 queries returns a List<Row> as the root. Seeded: the same file every time (the base and new harnesses must run the same program).
# Usage: fast/webmany-types.py > WebManyTypes.cs   (setup.sh does this)
import random

N = 200
rnd = random.Random(20261115)
AREAS = ["Orders", "Customers", "Invoices", "Products", "Shipments", "Payments", "Inventory", "Users", "Reports", "Catalog"]
SINGULAR = {"Orders": "Order", "Customers": "Customer", "Invoices": "Invoice", "Products": "Product", "Shipments": "Shipment",
            "Payments": "Payment", "Inventory": "Stock", "Users": "User", "Reports": "Report", "Catalog": "Category"}
QUERIES = ["Get", "Find", "Lookup", "Show", "Summarize", "List"]
COMMANDS = ["Create", "Update", "Cancel", "Approve", "Assign", "Import", "Archive", "Register"]
NAMES = ["Id", "Name", "Code", "Description", "CreatedAt", "UpdatedAt", "Status", "Amount", "Quantity", "Price", "Total", "CustomerId", "Email",
         "Phone", "IsActive", "Reference", "Remarks", "Weight", "Width", "Height", "Discount", "TaxRate", "Currency", "OwnerId", "Version",
         "ExternalId", "DueDate", "PaidAt", "Priority", "Category", "Tags", "Score", "Rank", "Country", "City", "Street", "Zip", "Iban",
         "Sku", "Barcode", "Supplier", "Warehouse", "Location", "Batch", "ExpiresAt", "Notes", "Title", "FirstName", "LastName", "Company",
         "VatNumber", "Balance", "Limit", "Count", "Ratio", "Latitude", "Longitude", "Language", "TimeZone", "Url", "Token", "Hash"]
# (C# type, weight)
SCALARS = [("int", 14), ("long", 4), ("string", 22), ("bool", 6), ("decimal", 8), ("DateTime", 7), ("Guid", 5), ("double", 4),
           ("int?", 4), ("State", 4), ("DateTime?", 2), ("decimal?", 2)]


def scalar():
    total = sum(w for _, w in SCALARS)
    x = rnd.uniform(0, total)
    for t, w in SCALARS:
        x -= w
        if x <= 0:
            return t
    return "string"


def width(kind):
    # mostly small classes, some medium, a few wide ones as real backends have them
    r = rnd.random()
    if kind == "item":
        return rnd.randint(3, 8)
    if kind == "request":
        return rnd.randint(2, 6) if r < 0.6 else rnd.randint(7, 14)
    return rnd.randint(3, 8) if r < 0.5 else rnd.randint(9, 20) if r < 0.88 else rnd.randint(21, 60)


def props(count, first="Id"):
    names = [first] if first else []
    pool = [n for n in NAMES if n not in names]
    rnd.shuffle(pool)
    while len(names) < count:
        names.append(pool.pop() if pool else "Field%d" % len(names))
    out = []
    for n in names:
        t = "int" if n == "Id" else "string" if n in ("Name", "Email", "Code") else "DateTime" if n == "CreatedAt" else scalar()
        out.append((t, n))
    return out


def cls(name, members, indent="    "):
    body = " ".join("public %s %s { get; set; }" % (t, n) for t, n in members)
    return "%spublic class %s { %s }\n" % (indent, name, body)


print("// Generated by webmany-types.py: the vertical slices of WebMany.cs.")
print("using LsMsgPackFormatters;\nusing Microsoft.AspNetCore.Builder;\nusing Microsoft.AspNetCore.Http;\nusing Microsoft.AspNetCore.Mvc;\nusing Microsoft.AspNetCore.Routing;")
print("using System;\nusing System.Collections.Generic;\n")
print("namespace Features.Shared\n{")
print("  public class Money { public decimal Amount { get; set; } public string Currency { get; set; } }")
print("  public class PostalAddress { public string Street { get; set; } public string City { get; set; } public string Zip { get; set; } public string Country { get; set; } }")
print("}\n")

slices = []  # (index, ns, class, verb kind, response root C# type, request type or None, list length)
for i in range(N):
    area = AREAS[i % len(AREAS)]
    query = i % 2 == 0
    verb = rnd.choice(QUERIES if query else COMMANDS)
    name = "%s%s%03d" % (verb, SINGULAR[area], i)
    listRoot = query and verb == "List"
    path = "%s/%s-%s-%s" % (area.lower(), verb.lower(), SINGULAR[area].lower(), chr(97 + i // 26) + chr(97 + i % 26))
    listLen = rnd.choice([0, 1, 2, 3, 5, 8, 12, 20, 40]) if rnd.random() < 0.9 else 100
    out = ["namespace Features.%s\n{\n" % area, "  public static class %s\n  {\n" % name]
    out.append("    public enum State { New, Active, Blocked, Closed }\n")
    if not query:
        req = props(width("request"))
        if rnd.random() < 0.35:
            out.append(cls("Line", props(width("item"), None)))
            req.append(("List<Line>", "Lines"))
        if rnd.random() < 0.2:
            req.append(("Features.Shared.PostalAddress", "Address"))
        out.append(cls("Request", req))
    if listRoot:
        out.append(cls("Row", props(width("item"))))
        root = "List<%s.Row>" % name
        rootFull = "List<Features.%s.%s.Row>" % (area, name)
    else:
        resp = props(width("response"))
        if rnd.random() < 0.45:
            out.append(cls("Item", props(width("item"), None)))
            resp.append(("List<Item>", "Items"))
        if rnd.random() < 0.25:
            resp.append(("Features.Shared.Money", "Total" + "Money"))
        if rnd.random() < 0.2:
            resp.append(("Features.Shared.PostalAddress", "Address"))
        out.append(cls("Response", resp))
        root = "%s.Response" % name
        rootFull = "Features.%s.%s" % (area, root)
    if query:
        out.append("    public static %s Handle(int id) => Data<%s>.Values[id & 3];\n" % (root, root))
    else:
        out.append("    public static %s Handle(Request request) => Data<%s>.Values[request.Id & 3];\n" % (root, root))
    out.append("  }\n\n")
    # the MVC controller of the slice (MVC finds only public top-level classes)
    out.append("  [ApiController]\n  [Route(\"m/%s\")]\n  public class %sController : ControllerBase\n  {\n" % (path, name))
    if query:
        out.append("    [HttpGet(\"{id:int}\")]\n    public %s Get(int id) => %s.Handle(id);\n" % (root, name))
    else:
        out.append("    [HttpPost]\n    public %s Post(%s.Request request) => %s.Handle(request);\n" % (root, name, name))
    out.append("  }\n}\n")
    print("".join(out))
    slices.append((i, "Features.%s.%s" % (area, name), query, rootFull, None if query else "%s.Request" % name, listLen, path))

print("public static class Data<T> { public static T[] Values; }\n")
print("static class Slices\n{")
print("  internal const int N = %d;" % N)
print("  /// <summary>Per slice: GET or POST, the response's declared type, the request's type (null for a query), the length of its lists, the path after /s/ or /m/.</summary>")
print("  internal static readonly (bool Get, Type Response, Type Request, int ListLength, string Path)[] All =\n  {")
for i, full, query, root, req, listLen, path in slices:
    ns = full.rsplit(".", 1)[0]
    print("    (%s, typeof(%s), %s, %d, \"%s\")," % ("true" if query else "false", root, "null" if req is None else "typeof(%s.%s)" % (ns, req), listLen, path))
print("  };\n")
print("  internal static void MapMinimal(IEndpointRouteBuilder app)\n  {")
for i, full, query, root, req, listLen, path in slices:
    ns = full.rsplit(".", 1)[0]
    if query:
        print("    app.MapGet(\"/s/%s/{id:int}\", (int id) => MsgPackResults.MsgPack(%s.Handle(id)));" % (path, full))
    else:
        print("    app.MapPost(\"/s/%s\", (MsgPackBody<%s.%s> body) => MsgPackResults.MsgPack(%s.Handle(body.Value)));" % (path, ns, req, full))
print("  }\n}")
